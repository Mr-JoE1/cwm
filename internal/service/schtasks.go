package service

import (
	"encoding/xml"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/Mr-JoE1/cwm/internal/gui/term"
)

// Windows names.
const (
	TaskName = "cwm agent"
	RunKey   = `HKCU\Software\Microsoft\Windows\CurrentVersion\Run`
	RunValue = "cwm"
)

// TaskXMLPath is where the generated task definition is kept (for
// schtasks /XML and for reference).
func (e Env) TaskXMLPath() string { return filepath.Join(e.Root, "state", "cwm-agent-task.xml") }

func xmlEscape(s string) string {
	var b strings.Builder
	_ = xml.EscapeText(&b, []byte(s))
	return b.String()
}

// taskTmpl is a Task Scheduler 1.2 definition: a logon trigger scoped to
// the current user (which a standard user may create — an any-user logon
// trigger needs admin), least privilege, interactive token (so the agent
// can open the user's browser), no run-time limit, one instance.
var taskTmpl = template.Must(template.New("task").Funcs(template.FuncMap{"x": xmlEscape}).Parse(
	`<?xml version="1.0" encoding="UTF-16"?>
<!-- ` + generatedBanner + ` -->
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>{{x .Description}}</Description>
    <URI>\{{x .Name}}</URI>
  </RegistrationInfo>
  <Triggers>
    <LogonTrigger>
      <Enabled>true</Enabled>
{{- if .UserID}}
      <UserId>{{x .UserID}}</UserId>
{{- end}}
      <Delay>PT5S</Delay>
    </LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
{{- if .UserID}}
      <UserId>{{x .UserID}}</UserId>
{{- end}}
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>false</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <IdleSettings>
      <StopOnIdleEnd>false</StopOnIdleEnd>
      <RestartOnIdle>false</RestartOnIdle>
    </IdleSettings>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <RunOnlyIfIdle>false</RunOnlyIfIdle>
    <WakeToRun>false</WakeToRun>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Priority>7</Priority>
    <RestartOnFailure>
      <Interval>PT1M</Interval>
      <Count>3</Count>
    </RestartOnFailure>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>{{x .Command}}</Command>
      <Arguments>{{x .Arguments}}</Arguments>
    </Exec>
  </Actions>
</Task>
`))

// winCmdLine joins args by the Windows command-line rules.
func winCmdLine(args []string) string {
	q := make([]string, len(args))
	for i, a := range args {
		q[i] = term.EscapeWindowsArg(a)
	}
	return strings.Join(q, " ")
}

// windowsExe prefers cwmd.exe (GUI subsystem: no console window at logon)
// next to cwm.exe.
func (e Env) windowsExe() (string, bool) {
	dir := e.Exe
	if i := strings.LastIndexAny(dir, `\/`); i >= 0 {
		dir = dir[:i]
	}
	d := dir + `\cwmd.exe`
	if e.exists(d) {
		return d, true
	}
	return e.Exe, false
}

func windowsInstall(e Env, o Options) (Plan, error) {
	if err := checkPath(e.Exe); err != nil {
		return Plan{}, err
	}
	exe, silent := e.windowsExe()
	var args []string
	desc := "cwm agent: Claude Workspace Manager dashboard, started at logon (generated by cwm service install)"
	switch {
	case o.OpenOnly:
		args = []string{"service", "open-url", o.URL}
		desc = "cwm: open the dashboard " + o.URL + " at logon (generated by cwm service install --open-only)"
	case o.NoOpen:
		args = []string{"agent", "--no-open"}
	default:
		args = []string{"agent", "--open"}
	}
	content, err := render(taskTmpl, map[string]string{
		"Description": desc, "Name": TaskName, "UserID": e.UserID,
		"Command": exe, "Arguments": winCmdLine(args),
	})
	if err != nil {
		return Plan{}, err
	}
	p := Plan{
		Files: []File{{Path: e.TaskXMLPath(), Content: content, Mode: 0o644, UTF16: true}},
		Commands: []Command{{
			Name: "schtasks.exe",
			Args: []string{"/Create", "/TN", TaskName, "/XML", e.TaskXMLPath(), "/F"},
			// Some locked-down machines refuse even per-user logon tasks;
			// the per-user Run key needs no rights at all.
			Fallback: []Command{{
				Name: "reg.exe",
				Args: []string{"add", RunKey, "/v", RunValue, "/t", "REG_SZ", "/d", winCmdLine(append([]string{exe}, args...)), "/f"},
			}},
		}},
	}
	if !silent {
		p.Notes = append(p.Notes, "cwmd.exe not found next to cwm.exe — the logon task runs cwm.exe, which shows a console window")
	}
	if e.CwmHome != "" {
		p.Notes = append(p.Notes, "CWM_HOME is set: make it a persistent user variable (setx CWM_HOME \""+e.CwmHome+"\") so the logon task sees it")
	}
	return p, nil
}

func windowsUninstall(e Env) Plan {
	return Plan{
		Pre: []Command{
			{Name: "schtasks.exe", Args: []string{"/End", "/TN", TaskName}, IgnoreError: true},
			{Name: "schtasks.exe", Args: []string{"/Delete", "/TN", TaskName, "/F"}, IgnoreError: true},
			{Name: "reg.exe", Args: []string{"delete", RunKey, "/v", RunValue, "/f"}, IgnoreError: true},
		},
		Remove: []string{e.TaskXMLPath()},
	}
}

func windowsControl(e Env, a Action) (Plan, bool) {
	if !e.exists(e.TaskXMLPath()) {
		return Plan{}, false
	}
	verb := "/Run"
	if a == Stop {
		verb = "/End"
	}
	return Plan{Commands: []Command{{Name: "schtasks.exe", Args: []string{verb, "/TN", TaskName}}}}, true
}

func windowsStatus(e Env) []Item {
	items := []Item{fileItem(e, "task definition", e.TaskXMLPath())}
	if e.Runner == nil {
		return items
	}
	if out, err := e.Runner.Run("schtasks.exe", "/Query", "/TN", TaskName, "/FO", "LIST"); err == nil {
		state := "registered"
		for _, line := range strings.Split(out, "\n") {
			if k, v, ok := strings.Cut(line, ":"); ok && strings.TrimSpace(k) == "Status" {
				state = strings.TrimSpace(v)
			}
		}
		items = append(items, Item{Name: "logon task", State: state, Detail: TaskName})
	} else {
		items = append(items, Item{Name: "logon task", State: "missing", Detail: TaskName})
	}
	if _, err := e.Runner.Run("reg.exe", "query", RunKey, "/v", RunValue); err == nil {
		items = append(items, Item{Name: "Run key (fallback)", State: "installed", Detail: RunKey + `\` + RunValue})
	}
	return items
}
