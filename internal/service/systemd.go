package service

import (
	"fmt"
	"path/filepath"
	"strconv"
	"strings"
	"text/template"
)

// Linux names.
const (
	UnitName        = "cwm-agent.service"
	DesktopName     = "cwm-dashboard.desktop"
	OpenerWaitSD    = "30" // with a systemd agent: give the unit time to come up
	OpenerWaitNoSD  = "5"  // without: start the agent ourselves soon
	generatedBanner = "Generated by `cwm service install` — remove with `cwm service uninstall`."
)

func (e Env) xdgConfig() string {
	if e.XDGConfig != "" {
		return e.XDGConfig
	}
	return filepath.Join(e.Home, ".config")
}

// UnitPath is ~/.config/systemd/user/cwm-agent.service.
func (e Env) UnitPath() string { return filepath.Join(e.xdgConfig(), "systemd", "user", UnitName) }

// DesktopPath is ~/.config/autostart/cwm-dashboard.desktop.
func (e Env) DesktopPath() string { return filepath.Join(e.xdgConfig(), "autostart", DesktopName) }

// HasSystemdUser reports a reachable systemd user manager: systemctl on
// PATH and the manager's private socket present. Pure filesystem checks —
// detection never runs a command.
func (e Env) HasSystemdUser() bool {
	if e.LookPath == nil {
		return false
	}
	if _, err := e.LookPath("systemctl"); err != nil {
		return false
	}
	rt := e.XDGRuntime
	if rt == "" {
		rt = filepath.Join("/run/user", strconv.Itoa(e.UID))
	}
	return e.exists(filepath.Join(rt, "systemd", "private"))
}

// sdQuote quotes one systemd ExecStart/Environment word: double quotes,
// C-style escapes, and the specifier (%) and variable ($) characters
// doubled so systemd passes them literally.
func sdQuote(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `%`, `%%`, `$`, `$$`)
	return `"` + r.Replace(s) + `"`
}

var unitTmpl = template.Must(template.New("unit").Funcs(template.FuncMap{"q": sdQuote}).Parse(
	`# ` + generatedBanner + `
[Unit]
Description=cwm agent (Claude Workspace Manager dashboard)
Documentation=https://github.com/Mr-JoE1/cwm

[Service]
Type=simple
ExecStart={{q .Exe}} agent --no-open
{{- if .CwmHome}}
Environment={{q (print "CWM_HOME=" .CwmHome)}}
{{- end}}
Restart=on-failure
RestartSec=5

[Install]
WantedBy=default.target
`))

// desktopUnsafe are characters the desktop-entry Exec key would need two
// layers of escaping for; paths containing them are refused instead.
const desktopUnsafe = "\"'`$\\%"

func desktopArg(s string) (string, error) {
	if strings.ContainsAny(s, desktopUnsafe) {
		return "", fmt.Errorf("service: %q contains a character the XDG autostart Exec line cannot carry (%s) — install cwm under a simpler path", s, desktopUnsafe)
	}
	if strings.ContainsAny(s, " \t<>~|&;*?#()") || s == "" {
		return `"` + s + `"`, nil
	}
	return s, nil
}

var desktopTmpl = template.Must(template.New("desktop").Parse(`# ` + generatedBanner + `
[Desktop Entry]
Type=Application
Name={{.Name}}
Comment={{.Comment}}
Exec={{.Exec}}
Terminal=false
NoDisplay=true
X-GNOME-Autostart-enabled=true
X-GNOME-Autostart-Delay=5
`))

// desktopExec builds the Exec line for argv (+ CWM_HOME via env).
func desktopExec(cwmHome string, argv []string) (string, error) {
	var parts []string
	if cwmHome != "" {
		v, err := desktopArg("CWM_HOME=" + cwmHome)
		if err != nil {
			return "", err
		}
		parts = append(parts, "env", v)
	}
	for _, a := range argv {
		v, err := desktopArg(a)
		if err != nil {
			return "", err
		}
		parts = append(parts, v)
	}
	return strings.Join(parts, " "), nil
}

func linuxInstall(e Env, o Options) (Plan, error) {
	if err := checkPath(e.Exe); err != nil {
		return Plan{}, err
	}
	if err := checkPath(e.CwmHome); err != nil {
		return Plan{}, err
	}
	var p Plan
	if o.OpenOnly {
		exec, err := desktopExec(e.CwmHome, []string{e.Exe, "service", "open-url", o.URL})
		if err != nil {
			return Plan{}, err
		}
		content, err := render(desktopTmpl, map[string]string{
			"Name": "cwm dashboard opener", "Comment": "Open the cwm dashboard (" + o.URL + ") at login", "Exec": exec,
		})
		if err != nil {
			return Plan{}, err
		}
		p.Files = append(p.Files, File{Path: e.DesktopPath(), Content: content, Mode: 0o644})
		p.Notes = append(p.Notes, "only the browser opener was installed; the agent itself runs elsewhere (e.g. a container)")
		return p, nil
	}

	sd := e.HasSystemdUser()
	if sd {
		unit, err := render(unitTmpl, e)
		if err != nil {
			return Plan{}, err
		}
		p.Files = append(p.Files, File{Path: e.UnitPath(), Content: unit, Mode: 0o644})
		p.Commands = append(p.Commands,
			Command{Name: "systemctl", Args: []string{"--user", "daemon-reload"}},
			Command{Name: "systemctl", Args: []string{"--user", "enable", "--now", UnitName}},
		)
	}
	switch {
	case sd && o.NoOpen:
		// The unit alone starts the agent; no opener wanted.
		p.Remove = append(p.Remove, e.DesktopPath())
	default:
		wait := OpenerWaitSD
		if !sd {
			wait = OpenerWaitNoSD
		}
		argv := []string{e.Exe, "dashboard", "--wait", wait}
		comment := "Open the cwm dashboard at login"
		if o.NoOpen {
			argv = append(argv, "--no-open") // no systemd: this entry is what starts the agent
			comment = "Start the cwm agent at login"
		}
		exec, err := desktopExec(e.CwmHome, argv)
		if err != nil {
			return Plan{}, err
		}
		content, err := render(desktopTmpl, map[string]string{"Name": "cwm dashboard", "Comment": comment, "Exec": exec})
		if err != nil {
			return Plan{}, err
		}
		p.Files = append(p.Files, File{Path: e.DesktopPath(), Content: content, Mode: 0o644})
	}
	if !sd {
		p.Notes = append(p.Notes, "no systemd user session found: the XDG autostart entry starts the agent at your next graphical login (run `cwm dashboard` to start it now)")
	}
	return p, nil
}

func linuxUninstall(e Env) Plan {
	p := Plan{Remove: []string{e.UnitPath(), e.DesktopPath()}}
	if e.HasSystemdUser() {
		// disable needs the unit file, so it runs before the removal.
		p.Pre = []Command{{Name: "systemctl", Args: []string{"--user", "disable", "--now", UnitName}, IgnoreError: true}}
		p.Commands = []Command{{Name: "systemctl", Args: []string{"--user", "daemon-reload"}, IgnoreError: true}}
	}
	return p
}

func linuxControl(e Env, a Action) (Plan, bool) {
	if !e.HasSystemdUser() || !e.exists(e.UnitPath()) {
		return Plan{}, false
	}
	return Plan{Commands: []Command{{Name: "systemctl", Args: []string{"--user", string(a), UnitName}}}}, true
}

func linuxStatus(e Env) []Item {
	items := []Item{fileItem(e, "systemd unit", e.UnitPath()), fileItem(e, "login opener", e.DesktopPath())}
	if !e.HasSystemdUser() {
		items = append(items, Item{Name: "systemd --user", State: "unavailable", Detail: "XDG autostart only"})
		return items
	}
	if e.Runner != nil && e.exists(e.UnitPath()) {
		active, _ := e.Runner.Run("systemctl", "--user", "is-active", UnitName)
		enabled, _ := e.Runner.Run("systemctl", "--user", "is-enabled", UnitName)
		items = append(items, Item{Name: "systemd --user", State: strings.TrimSpace(active), Detail: "enabled: " + strings.TrimSpace(enabled)})
	}
	return items
}
