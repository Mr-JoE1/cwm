func decodeUTF16(t *testing.T, b []byte) string {
	t.Helper()
	if len(b) < 2 || b[0] != 0xFF || b[1] != 0xFE || len(b)%2 != 0 {
		t.Fatalf("not UTF-16LE with BOM: % x", b[:min(4, len(b))])
	}
	u := make([]uint16, 0, len(b)/2-1)
	for i := 2; i < len(b); i += 2 {
		u = append(u, uint16(b[i])|uint16(b[i+1])<<8)
	}
	return string(utf16.Decode(u))
}

func TestWindowsTaskInstall(t *testing.T) {
	e, r, _ := testEnv(t, "windows", nil)
	cwmd := `C:\Users\jane\AppData\Local\cwm\bin\cwmd.exe`
	e.Stat = func(p string) (os.FileInfo, error) {
		if p == cwmd {
			return fakeInfo{"cwmd.exe"}, nil
		}
		return os.Stat(p)
	}
	p, err := BuildInstall(e, Options{})
	if err != nil {
		t.Fatal(err)
	}
	if len(p.Files) != 1 || !p.Files[0].UTF16 || p.Files[0].Path != filepath.Join(e.Root, "state", "cwm-agent-task.xml") {
		t.Fatalf("files = %+v", p.Files)
	}
	x := decodeUTF16(t, p.Files[0].Bytes())
	if x != string(p.Files[0].Content) {
		t.Error("UTF-16 encoding does not round-trip")
	}
	for _, want := range []string{
		`<?xml version="1.0" encoding="UTF-16"?>`,
		`<LogonTrigger>`, `<UserId>DESKTOP-1\jane</UserId>`,
		`<LogonType>InteractiveToken</LogonType>`, `<RunLevel>LeastPrivilege</RunLevel>`,
		`<MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>`, `<ExecutionTimeLimit>PT0S</ExecutionTimeLimit>`,
		`<DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>`,
		"<Command>" + cwmd + "</Command>", `<Arguments>agent --open</Arguments>`,
	} {
		if !strings.Contains(x, want) {
			t.Errorf("task XML lacks %q:\n%s", want, x)
		}
	}
	// Well-formed XML.
	dec := xml.NewDecoder(strings.NewReader(strings.Replace(x, `encoding="UTF-16"`, `encoding="UTF-8"`, 1)))
	for {
		if _, err := dec.Token(); err != nil {
			if err.Error() != "EOF" {
				t.Errorf("task XML malformed: %v", err)
			}
			break
		}
	}
	if len(p.Notes) != 0 {
		t.Errorf("notes with cwmd present: %v", p.Notes)
	}
	create := "schtasks.exe /Create /TN cwm agent /XML " + e.TaskXMLPath() + " /F"
	if cmds(p.Commands) != create {
		t.Errorf("commands = %q", cmds(p.Commands))
	}
	// schtasks refuses → the Run-key fallback, with a properly quoted command line.
	r.fail[create] = true
	if err := e.Apply(p); err != nil {
		t.Fatalf("apply with fallback: %v", err)
	}
	if len(r.calls) != 2 || !strings.HasPrefix(r.calls[1], `reg.exe add HKCU\Software\Microsoft\Windows\CurrentVersion\Run /v cwm /t REG_SZ /d `) ||
		!strings.HasSuffix(r.calls[1], " agent --open /f") {
		t.Errorf("fallback calls = %q", r.calls)
	}
	if fb := p.Commands[0].Fallback[0].Args[7]; fb != winCmdLine([]string{cwmd, "agent", "--open"}) {
		t.Errorf("Run value = %q", fb)
	}
}

