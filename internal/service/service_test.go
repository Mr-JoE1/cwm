// fakeRunner records every command and fails the ones listed in fail.
type fakeRunner struct {
	calls []string
	fail  map[string]bool
	out   map[string]string
}

func (f *fakeRunner) Run(name string, args ...string) (string, error) {
	c := strings.Join(append([]string{name}, args...), " ")
	f.calls = append(f.calls, c)
	if f.fail[c] {
		return "access denied", errors.New("exit status 1")
	}
	return f.out[c], nil
}

type fakeInfo struct{ name string }

func (i fakeInfo) Name() string       { return i.name }
func (i fakeInfo) Size() int64        { return 0 }
func (i fakeInfo) Mode() fs.FileMode  { return 0o644 }
func (i fakeInfo) ModTime() time.Time { return time.Time{} }
func (i fakeInfo) IsDir() bool        { return false }
func (i fakeInfo) Sys() any           { return nil }

// testEnv builds a hermetic Env: present lists the paths Stat reports as
// existing (besides real files under the temp home), onPath the commands
// LookPath finds.
func testEnv(t *testing.T, goos string, present []string, onPath ...string) (Env, *fakeRunner, *bytes.Buffer) {
	t.Helper()
	home := t.TempDir()
	r := &fakeRunner{fail: map[string]bool{}, out: map[string]string{}}
	var out bytes.Buffer
	exe := "/home/jane/.local/bin/cwm"
	if goos == "windows" {
		exe = `C:\Users\jane\AppData\Local\cwm\bin\cwm.exe`
	}
	return Env{
		GOOS:       goos,
		Home:       home,
		Root:       filepath.Join(home, ".cwm"),
		Exe:        exe,
		UID:        501,
		UserID:     `DESKTOP-1\jane`,
		XDGRuntime: filepath.Join(home, "run"),
		LookPath: func(f string) (string, error) {
			for _, p := range onPath {
				if p == f {
					return "/usr/bin/" + f, nil
				}
			}
			return "", exec.ErrNotFound
		},
		Stat: func(p string) (os.FileInfo, error) {
			for _, q := range present {
				if q == p {
					return fakeInfo{filepath.Base(p)}, nil
				}
			}
			return os.Stat(p)
		},
		Runner: r,
		Out:    &out,
	}, r, &out
}

func withSystemd(t *testing.T) (Env, *fakeRunner, *bytes.Buffer) {
	t.Helper()
	e, r, out := testEnv(t, "linux", nil, "systemctl")
	e.Stat = func(p string) (os.FileInfo, error) {
		if p == filepath.Join(e.XDGRuntime, "systemd", "private") {
			return fakeInfo{"private"}, nil
		}
		return os.Stat(p)
	}
	return e, r, out
}

func fileByPath(t *testing.T, p Plan, path string) string {
	t.Helper()
	for _, f := range p.Files {
		if f.Path == path {
			return string(f.Content)
		}
	}
	t.Fatalf("plan has no file %s (files: %v)", path, p.Files)
	return ""
}

func cmds(p []Command) string {
	s := make([]string, len(p))
	for i, c := range p {
		s[i] = strings.Join(append([]string{c.Name}, c.Args...), " ")
	}
	return strings.Join(s, "\n")
}

func TestLinuxSystemdInstall(t *testing.T) {
	e, r, _ := withSystemd(t)
	e.CwmHome = "/home/jane/cwm data/%h$x"
	e.Exe = "/home/jane/.local/bin/cwm"
	// --no-open: the unit alone (the odd CWM_HOME could not go into the
	// desktop entry — see TestLinuxDesktopRefusesUnsafePaths).
	p, err := BuildInstall(e, Options{NoOpen: true})
	if err != nil {
		t.Fatal(err)
	}
	unit := fileByPath(t, p, filepath.Join(e.Home, ".config", "systemd", "user", "cwm-agent.service"))
	for _, want := range []string{
		"ExecStart=\"/home/jane/.local/bin/cwm\" agent --no-open\n",
		"Environment=\"CWM_HOME=/home/jane/cwm data/%%h$$x\"\n",
		"Restart=on-failure\n", "WantedBy=default.target\n", "Type=simple\n", "# Generated by `cwm service install`",
	} {
		if !strings.Contains(unit, want) {
			t.Errorf("unit lacks %q:\n%s", want, unit)
		}
	}
	if _, err := BuildInstall(e, Options{}); err == nil {
		t.Error("CWM_HOME with % and $ accepted for the desktop entry")
	}
	e.CwmHome = ""
	p, err = BuildInstall(e, Options{})
	if err != nil {
		t.Fatal(err)
	}
	desk := fileByPath(t, p, filepath.Join(e.Home, ".config", "autostart", "cwm-dashboard.desktop"))
	for _, want := range []string{"[Desktop Entry]\n", "Type=Application\n", "Exec=/home/jane/.local/bin/cwm dashboard --wait 30\n", "Terminal=false\n"} {
		if !strings.Contains(desk, want) {
			t.Errorf("desktop entry lacks %q:\n%s", want, desk)
		}
	}
	if got := cmds(p.Commands); got != "systemctl --user daemon-reload\nsystemctl --user enable --now cwm-agent.service" {
		t.Errorf("commands:\n%s", got)
	}
	if err := e.Apply(p); err != nil {
		t.Fatal(err)
	}
	if strings.Join(r.calls, "\n") != cmds(p.Commands) {
		t.Errorf("runner calls:\n%s", strings.Join(r.calls, "\n"))
	}
	for _, f := range p.Files {
		data, err := os.ReadFile(f.Path)
		if err != nil || string(data) != string(f.Content) {
			t.Errorf("%s not written: %v", f.Path, err)
		}
	}
}

